// Browser acceptance for the application UI over a saved graph. No target code executes.
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const out=path.resolve('output/frontend-review');fs.mkdirSync(out,{recursive:true});
const sid=JSON.parse(fs.readFileSync(process.env.SNAPSHOT_SUMMARY||'output/resource-responsibilities/gitdiagram-summary.json','utf8')).snapshot_id;
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'chrome'});
 try {
  const page=await browser.newPage({viewport:{width:1600,height:1150}}),errors=[];
  let submissions=0;
  page.on('pageerror',e=>errors.push(String(e)));
  page.on('request',r=>{if(r.method()==='POST'&&r.url().includes('/analyze/'))submissions++;});
  page.on('response',r=>{if(r.status()>=400&&r.url().includes('/api/'))errors.push(r.status()+' '+r.url());});
  await page.goto(process.env.APP_URL || 'http://127.0.0.1:5182/');
  await page.locator('.history button').filter({hasText:sid.slice(0,12)}).click();
  await page.getByRole('heading',{name:'Overall architecture',exact:true}).waitFor();
  await page.locator('.react-flow__node').first().waitFor();
  assert.equal(await page.locator('.hierarchy-explorer').count(),0);
  assert.equal(await page.locator('.workflow-controls').count(),0);
  assert.equal(await page.locator('.evidence-panel').count(),0);
  assert.ok(await page.locator('.react-flow__node').count()<=18);
  assert.equal(await page.locator('.node-kind').filter({hasText:/^FUNCTION$|^METHOD$|^CLASS$/}).count(),0);
  assert.ok(await page.locator('.node-kind').filter({hasText:'DERIVED RESPONSIBILITY'}).count()>0);
  const canonical=JSON.parse(fs.readFileSync(process.env.CANONICAL_GRAPH||'output/resource-responsibilities/gitdiagram-analysis.json','utf8'));
  const nodeIds=new Set(canonical.entities.map(n=>n.id)),edgeIds=new Set(canonical.edges.map(e=>e.id));
  for(const id of await page.locator('.react-flow__node').evaluateAll(nodes=>nodes.map(n=>n.dataset.id)))assert.ok(nodeIds.has(id),'Invented overview node');
  for(const id of await page.locator('.react-flow__edge').evaluateAll(edges=>edges.map(e=>e.dataset.id||e.dataset.testid?.replace(/^rf__edge-/,''))))assert.ok(edgeIds.has(id),'Overview edge lacks a canonical identity: '+id);
  await page.screenshot({path:path.join(out,'overview.png'),fullPage:true});
  await page.locator('.http-destinations > summary').click();
  await page.locator('.http-destinations button').first().click();
  await page.locator('.citation').first().waitFor();
  await page.getByRole('button',{name:'Close inspector',exact:true}).click();
  await page.locator('.http-destinations > summary').click();
  await page.locator('.node-label').filter({hasText:'API handling'}).first().click();
  await page.getByRole('complementary',{name:'Evidence inspector'}).waitFor();
  await page.locator('.citation').first().waitFor();
  await page.getByRole('button',{name:'Close inspector',exact:true}).click();
  await page.getByRole('button',{name:'Workflows',exact:true}).click();
  await page.getByLabel('Workflow component').selectOption({label:'Client-side requests · gitdiagram'});
  await page.locator('.react-flow__node').first().waitFor();
  await page.locator('.node-kind').filter({hasText:/FUNCTION|METHOD/}).first().waitFor();
  assert.equal(await page.locator('.hierarchy-explorer').count(),0);
  await page.screenshot({path:path.join(out,'workflow.png'),fullPage:true});
  await page.getByRole('button',{name:'Code explorer',exact:true}).click();
  await page.getByRole('complementary',{name:'Repository explorer'}).waitFor();
  await page.getByRole('button',{name:'Declared deployment',exact:true}).click();
  await page.getByRole('region',{name:'Declared deployment diagram'}).waitFor();
  await page.locator('.react-flow__node').first().waitFor();
  await page.getByRole('button',{name:'Needs context',exact:true}).click();
  await page.locator('.issue-row').first().waitFor();
  await page.locator('.issue-row').first().click();
  await page.locator('.citation').first().waitFor();
  await page.getByRole('button',{name:'Diagnostics',exact:true}).click();
  await page.getByRole('heading',{name:'Analysis details',exact:true}).waitFor();
  await page.getByRole('button',{name:'Architecture overview',exact:true}).click();
  await page.locator('.node-kind').filter({hasText:'DERIVED RESPONSIBILITY'}).first().waitFor();
  assert.equal(await page.locator('.hierarchy-explorer').count(),0);
  await page.reload();
  await page.getByRole('heading',{name:'Overall architecture',exact:true}).waitFor();
  await page.locator('.react-flow__node').first().waitFor();
  assert.equal(await page.evaluate(()=>localStorage.getItem('analysis-id')),sid);
  await page.setViewportSize({width:1100,height:900});
  await page.screenshot({path:path.join(out,'overview-1100.png'),fullPage:true});
  assert.equal(submissions,0);assert.deepEqual(errors,[]);
  const report={snapshot_id:sid,tabs_verified:6,overview_nodes:await page.locator('.react-flow__node').count(),
   evidence_verified:true,http_destination_evidence_verified:true,canonical_diagram_ids_verified:true,workflow_component_verified:true,saved_analysis_reopened:true,analysis_submissions:submissions,browser_errors:errors};
  fs.writeFileSync(path.join(out,'browser-results.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
